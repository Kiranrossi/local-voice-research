"""Builds the comparison tables for the report from the committed results.

    python src/analyze.py            -> writes results/summary.md

Every number in the report comes from this script, which reads only files under results/.
"""
import collections
import csv
import json
import math
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import harness as H  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent / "results"
OUT = ROOT / "summary.md"

# Key facts per model that are not measured (licence, Tamil support), from model cards.
FACTS = {
    "whisper-large-v3-turbo": {"licence": "MIT", "lic": 1.0, "tamil": True},
    "whisper-large-v3-turbo+vad": {"licence": "MIT", "lic": 1.0, "tamil": True},
    "parakeet-tdt-0.6b-v2": {"licence": "CC-BY-4.0", "lic": 0.9, "tamil": False},
    "parakeet-tdt-0.6b-v3": {"licence": "CC-BY-4.0", "lic": 0.9, "tamil": False},
    "qwen3-asr-1.7B": {"licence": "Apache-2.0", "lic": 1.0, "tamil": False},
    "qwen3-asr-0.6B": {"licence": "Apache-2.0", "lic": 1.0, "tamil": False},
    "moonshine-streaming-medium": {"licence": "MIT", "lic": 1.0, "tamil": False},
    "moonshine-streaming-tiny": {"licence": "MIT", "lic": 1.0, "tamil": False},
}

# Entities in the 10 English stress sentences (normalised form). An entity counts as correct
# only if it appears exactly in the normalised model output.
ENTITIES = {
    "en_01": ["2499", "karthikeyan", "15th august"],
    "en_02": ["chennai egmore", "tiruchirappalli", "3rd december"],
    "en_03": ["9840123456", "subramanian"],
    "en_04": ["tn 4471 b"],
    "en_05": ["745 pm", "lic", "12350"],
    "en_06": ["thiruvananthapuram", "kanyakumari"],
    "en_07": ["venkataraman", "1030 am", "2nd november"],
    "en_08": ["one.5 lakh", "hdfc", "4421"],
    "en_09": ["coimbatore", "3 days"],
    "en_10": ["2 kg", "500 grams", "paneer", "bigbasket"],
}
ENTITY_KIND = {"2499": "amount", "12350": "amount", "one.5 lakh": "amount", "9840123456": "number",
               "tn 4471 b": "number", "4421": "number", "745 pm": "time", "1030 am": "time"}

PROFILE_NAME = {"nvidia_gpu": "NVIDIA T4 GPU", "apple_silicon": "Apple M2 GPU (MLX)",
                "cpu": "CPU only (M2, 4 threads)", "apple_coreml": "Apple M2 CoreML + CPU"}


def read_csv(p):
    with open(p, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def outputs(folder, run_id):
    p = ROOT / folder / "outputs" / f"{run_id}.jsonl"
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]


def f(x, pct=False, nd=2):
    if x in ("", None) or (isinstance(x, float) and math.isnan(x)):
        return "–"
    x = float(x)
    return f"{x * 100:.1f}%" if pct else f"{x:.{nd}f}"


def stt_rows():
    rows = []
    for folder in ("colab_t4", "mac_m2"):
        for r in read_csv(ROOT / folder / "results_scored.csv"):
            if r.get("task", "stt") == "stt":
                r["_folder"] = folder
                rows.append(r)
    return rows


def wer_on_ids(folder, run_id, ids):
    errs, lens = [], []
    for o in outputs(folder, run_id):
        if o["id"] in ids:
            ref, hyp = H.normalise_en(o["ref"]), H.normalise_en(o["hyp"])
            if ref:
                we, wl, _, _ = H.utterance_errors(ref, hyp)
                errs.append(we); lens.append(wl)
    return H.corpus_rate(errs, lens)


def entity_scores(folder, run_id):
    hit, total, by_kind = 0, 0, collections.Counter()
    kind_total = collections.Counter()
    for o in outputs(folder, run_id):
        hyp = H.normalise_en(o["hyp"])
        for e in ENTITIES.get(o["id"], []):
            k = ENTITY_KIND.get(e, "name/word")
            total += 1; kind_total[k] += 1
            if f" {e} " in f" {hyp} ":
                hit += 1; by_kind[k] += 1
    return hit, total, by_kind, kind_total


def main():
    rows = stt_rows()
    idx = collections.defaultdict(dict)  # (model, profile, runtime) -> test_set -> row
    for r in rows:
        idx[(r["model"], r["hardware_profile"], r["runtime"], r["_folder"])][r["test_set"]] = r

    lines = ["# Results summary", "",
             "Generated by `src/analyze.py` from the files in `results/`. Scoring: Whisper English normaliser + "
             "Indian-English formatting rules (v2). WER = word error rate (lower is better); RTF = processing time ÷ "
             "audio length (below 1 is faster than real time); latency = median per sentence, batch size 1.", ""]

    # ---------------------------------------------------------------- STT by profile
    lines += ["## STT: all runs by hardware profile", ""]
    for prof in ("nvidia_gpu", "apple_silicon", "apple_coreml", "cpu"):
        sel = [(k, v) for k, v in idx.items() if k[1] == prof]
        if not sel:
            continue
        lines += [f"### {PROFILE_NAME[prof]}", "",
                  "| Model | Runtime | LibriSpeech WER | Svarah WER (95% CI) | Own clips WER | Hallucination (no-speech) | Latency | RTF | Peak memory |",
                  "|---|---|---|---|---|---|---|---|---|"]
        sel.sort(key=lambda kv: float(kv[1].get("svarah", {}).get("wer") or 9))
        for (model, _, runtime, _), ts in sel:
            sv, lb, own, nz = ts.get("svarah", {}), ts.get("librispeech", {}), ts.get("own_en", {}), ts.get("noise", {})
            ci = f" ({f(sv.get('wer_ci_low'), True)}–{f(sv.get('wer_ci_high'), True)})" if sv else ""
            n_sv = f" n={sv['n_clips']}" if sv and sv.get("n_clips") not in ("150",) else ""
            lines.append(f"| {model} | {runtime} | {f(lb.get('wer'), True)} | {f(sv.get('wer'), True)}{ci}{n_sv} | "
                         f"{f(own.get('wer'), True)} | {f(nz.get('hallucination_rate'), True) if nz else '–'} | "
                         f"{f(sv.get('latency_median_s') or own.get('latency_median_s'))} s | {f(sv.get('rtf') or own.get('rtf'), nd=3)} | "
                         f"{f(sv.get('peak_mem_gb') or own.get('peak_mem_gb'), nd=1)} GB |")
        lines.append("")

    # ---------------------------------------------------------------- same 50 clips
    ids50 = {f"svarah_{i:03d}" for i in range(50)}
    lines += ["## Same 50 Svarah clips on every platform", "",
              "The Mac runs used the first 50 of the 150 Svarah clips; this table scores every run on exactly those 50, "
              "so accuracy differences come from the platform or quantisation, not the sample.", "",
              "| Model | Platform | Runtime | Svarah-50 WER | Latency |", "|---|---|---|---|---|"]
    for (model, prof, runtime, folder), ts in sorted(idx.items()):
        if "svarah" in ts and model in ("whisper-large-v3-turbo", "whisper-large-v3-turbo+vad", "parakeet-tdt-0.6b-v2", "moonshine-streaming-medium"):
            w = wer_on_ids(folder, ts["svarah"]["run_id"], ids50)
            lines.append(f"| {model} | {PROFILE_NAME[prof]} | {runtime} | {f(w, True)} | {f(ts['svarah']['latency_median_s'])} s |")
    lines.append("")

    # ---------------------------------------------------------------- entities
    lines += ["## Entity accuracy on the 10 English stress sentences", "",
              f"{sum(len(v) for v in ENTITIES.values())} entities: amounts, phone/reference numbers, times, and Indian names/places. "
              "Correct = appears exactly in the normalised output.", "",
              "| Model | Platform | All entities | Amounts | Numbers | Times | Names/words |", "|---|---|---|---|---|---|---|"]
    ent_rows = []
    for (model, prof, runtime, folder), ts in idx.items():
        if "own_en" in ts:
            hit, tot, bk, kt = entity_scores(folder, ts["own_en"]["run_id"])
            ent_rows.append((hit / tot, model, prof, hit, tot, bk, kt))
    for share, model, prof, hit, tot, bk, kt in sorted(ent_rows, reverse=True):
        cells = " | ".join(f"{bk[k]}/{kt[k]}" for k in ("amount", "number", "time", "name/word"))
        lines.append(f"| {model} | {PROFILE_NAME[prof]} | **{hit}/{tot}** ({share:.0%}) | {cells} |")
    lines.append("")

    # ---------------------------------------------------------------- TTS
    tts_scored = {r["audio_dir"].split("__")[0]: r for r in read_csv(ROOT / "colab_t4" / "tts_scored.csv")}
    speed = {}
    for folder in ("colab_t4", "mac_m2"):
        for r in read_csv(ROOT / folder / "results.csv"):
            if r["task"] == "tts" and r["rtf"]:
                speed[(r["model"], r["hardware_profile"] if "CPU" not in r["runtime"] else "cpu", folder)] = r
    listen = collections.defaultdict(list)
    codes = {"m1": "kokoro-82m", "m2": "chatterbox", "m3": "qwen3-tts-0.6b", "m4": "voxcpm2"}
    n_listeners = 0
    lp = ROOT / "listening" / "responses.txt"
    if lp.exists():
        for line in lp.read_text(encoding="utf-8").splitlines():
            if line.startswith("VLT1"):
                n_listeners += 1
                for item in line.split(";", 3)[3].split(","):
                    k, v = item.split("=")
                    listen[codes[k.rsplit("_", 1)[1]]].append(int(v[0]))
    lines += ["## TTS: quality, speed and hardware", "",
              f"Round-trip WER: Whisper large-v3-turbo transcribes each generated clip (20 sentences). UTMOS: automatic "
              f"naturalness prediction (1 to 5). Human MOS: blind listening test, {n_listeners} listener(s), 8 clips per model.", "",
              "| Model | Human MOS | UTMOS | Round-trip WER (everyday / stress) | Measured on | RTF | Per sentence | Peak memory |",
              "|---|---|---|---|---|---|---|---|"]
    slug = {"kokoro-82m": "kokoro-82m", "chatterbox": "chatterbox", "qwen3-tts-0.6b": "qwen3-tts-0-6b", "voxcpm2": "voxcpm2"}
    for model in ("kokoro-82m", "chatterbox", "qwen3-tts-0.6b", "voxcpm2"):
        q = tts_scored.get(slug[model], {})
        h = listen.get(model, [])
        sp = [v for k, v in speed.items() if k[0] == model]
        best = min(sp, key=lambda r: float(r["rtf"])) if sp else {}
        where = ("M2 CPU" if "mac" in best.get("device_name", "").lower() or "Apple" in best.get("device_name", "") else best.get("device_name", ""))
        lines.append(f"| {model} | {f(sum(h) / len(h)) if h else '–'} | {f(q.get('utmos_mean'))} | "
                     f"{f(q.get('roundtrip_wer_everyday'), True)} / {f(q.get('roundtrip_wer_stress'), True)} | {where} | "
                     f"{f(best.get('rtf'))} | {f(best.get('latency_median_s'), nd=1)} s | {f(best.get('peak_mem_gb'), nd=1)} GB |")
    lines.append("")

    # ---------------------------------------------------------------- weighted STT score
    lines += ["## Weighted STT score per hardware profile", "",
              "Weights from the research plan: accuracy 30% (Svarah WER), speed 25% (median latency, log scale), licence 20%, "
              "Indian/Tamil readiness 15% (own-clip WER and Tamil support, half each), deployability 10% "
              "(no hallucination without extra components = 1, needs a VAD = 0.5). Each criterion is min-max scaled "
              "across the candidates on that profile (best = 1). Sensitivity: the ranking with accuracy at 50% "
              "(speed 15%, licence 15%, readiness 15%, deployability 5%). Hard gates, applied before scoring: commercial-use "
              "licence (all STT candidates pass) and real time (RTF below 1).", ""]
    groups = {"nvidia_gpu": ("nvidia_gpu",), "apple": ("apple_silicon", "apple_coreml"), "cpu": ("cpu",)}
    gname = {"nvidia_gpu": PROFILE_NAME["nvidia_gpu"], "apple": "Apple M2, best accelerator per model (MLX or CoreML)",
             "cpu": PROFILE_NAME["cpu"]}
    for prof, members in groups.items():
        cands, gated = [], []
        for (model, p, runtime, folder), ts in idx.items():
            if p not in members or "svarah" not in ts or model not in FACTS:
                continue
            if float(ts["svarah"]["rtf"]) >= 1.0:  # real-time gate: must keep up with speech
                gated.append(f"{model} ({runtime}): RTF {float(ts['svarah']['rtf']):.2f}, {float(ts['svarah']['latency_median_s']):.1f} s per sentence")
                continue
            fa = FACTS[model]
            hall = float(ts.get("noise", {}).get("hallucination_rate") or 0)
            cands.append({"model": model, "runtime": runtime, "acc": float(ts["svarah"]["wer"]),
                          "lat": float(ts["svarah"]["latency_median_s"]), "lic": fa["lic"],
                          "own": float(ts.get("own_en", {}).get("wer") or 1), "tamil": 1.0 if fa["tamil"] else 0.0,
                          "dep": 1.0 if hall == 0 else 0.5})
        if not cands:
            continue

        def scale(key, lower_better=True, log=False):
            vals = [math.log(c[key]) if log else c[key] for c in cands]
            lo, hi = min(vals), max(vals)
            for c, v in zip(cands, vals):
                c["s_" + key] = 1.0 if hi == lo else ((hi - v) / (hi - lo) if lower_better else (v - lo) / (hi - lo))
        scale("acc"); scale("lat", log=True); scale("own")
        for c in cands:
            ready = 0.5 * c["s_own"] + 0.5 * c["tamil"]
            c["base"] = 0.30 * c["s_acc"] + 0.25 * c["s_lat"] + 0.20 * c["lic"] + 0.15 * ready + 0.10 * c["dep"]
            c["sens"] = 0.50 * c["s_acc"] + 0.15 * c["s_lat"] + 0.15 * c["lic"] + 0.15 * ready + 0.05 * c["dep"]
        cands.sort(key=lambda c: -c["base"])
        sens_rank = {c["model"] + c["runtime"]: i + 1 for i, c in enumerate(sorted(cands, key=lambda c: -c["sens"]))}
        lines += [f"### {gname[prof]}", "", "| Rank | Model | Runtime | Score | Rank with accuracy at 50% |", "|---|---|---|---|---|"]
        for i, c in enumerate(cands, 1):
            lines.append(f"| {i} | {c['model']} | {c['runtime']} | {c['base']:.2f} | {sens_rank[c['model'] + c['runtime']]} |")
        if gated:
            lines += ["", "Excluded by the real-time gate (RTF must be below 1 for a live assistant): " + "; ".join(gated) + "."]
        lines.append("")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
